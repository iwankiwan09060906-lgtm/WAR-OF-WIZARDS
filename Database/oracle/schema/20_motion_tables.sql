	"KIND" VARCHAR2(10 CHAR) NOT NULL ENABLE,
	"SAMPLE_COUNT" NUMBER(19,0) NOT NULL ENABLE,
	"SHA256" VARCHAR2(64 CHAR),
	"SIZE_BYTES" NUMBER(19,0) NOT NULL ENABLE,
